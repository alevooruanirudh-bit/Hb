"""
Exports trained models into the app:

  CNN            → public/models/cnn/model.json + weight shards (TF.js graph model, uint8-quantized weights)
                   public/models/model-info.json (version, input size, normalization, embedding size)
  XGBoost ×3     → src/ml/models/xgboostModel.ts      (m2cgen → JavaScript, wrapped in TypeScript)
  Random Forest  → src/ml/models/randomForestModel.ts (m2cgen → JavaScript, wrapped in TypeScript)

Every generated tree model is VERIFIED: the exported JavaScript is executed in
Node on held-out rows and compared with the Python model's predictions.

Usage:
    python export.py [--version 2026.10-a] [--skip-cnn] [--dry-run]
Then rebuild the app (npm run build) and set VITE_USE_MOCK_MODELS=false
(or Settings → Model source → Trained).
"""
from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

import joblib
import numpy as np

from common import APP_ROOT, ARTIFACTS, COLOR_FEATURE_NAMES, FEAT, PRE

MODELS_TS = APP_ROOT / "src/ml/models"
PUBLIC_MODELS = APP_ROOT / "public/models"

HEADER = """/* eslint-disable */
// @ts-nocheck
/**
 * GENERATED by training/export.py on {date} — do not edit by hand.
 * {desc}
 * Input layout: {layout}
 */
export const IS_PLACEHOLDER: boolean = false;
export const MODEL_VERSION: string = '{version}';
export const FEATURE_COUNT: number = {n_features};
/** Whether the input starts with a CNN embedding (false = colour features only). */
export const USES_CNN: boolean = {uses_cnn};
/** Regions this model was trained on (others are not offered in the app). */
export const REGIONS: string[] = {regions};
/** XGBoost input ends with [age, sex]; see demographicFeatures() in the app. */
export const USES_DEMOGRAPHICS: boolean = {uses_demo};
"""


def m2cgen_js(model, fn_name: str) -> str:
    import m2cgen as m2c

    sys.setrecursionlimit(100_000)
    code = m2c.export_to_javascript(model, function_name=fn_name)
    return code.strip() + "\n"


def xgb_dump_to_js(model, fn_name: str) -> str:
    """Built-in XGBoost → JavaScript translator working from the booster's JSON dump.

    Used when the m2cgen output fails verification (m2cgen 0.10 mistranslates
    some XGBoost ≥ 2.0 models). Semantics match XGBoost exactly: float32
    comparisons (inputs are Math.fround-ed by the caller), `x < threshold`
    goes to the "yes" child, NaN follows the tree's default ("missing") branch,
    prediction = base_score + Σ leaves (identity link for regression).
    """
    booster = model.get_booster()
    base = float(json.loads(booster.save_config())["learner"]["learner_model_param"]["base_score"])

    def f32(v) -> str:
        return repr(float(np.float32(v)))

    def node_js(n) -> str:
        if "leaf" in n:
            return f32(n["leaf"])
        kids = {c["nodeid"]: c for c in n["children"]}
        i = int(n["split"][1:])
        t = f32(n["split_condition"])
        # NaN: `!(x >= t)` is true → yes-branch; `x < t` is false → no-branch.
        cond = f"!(x[{i}] >= {t})" if n.get("missing") == n["yes"] else f"x[{i}] < {t}"
        return f"({cond} ? {node_js(kids[n['yes']])} : {node_js(kids[n['no']])})"

    trees = [json.loads(t) for t in booster.get_dump(dump_format="json")]
    lines = [f"function {fn_name}(x) {{", f"  let s = {repr(base)};"]
    lines += [f"  s += {node_js(t)};" for t in trees]
    lines += ["  return s;", "}"]
    return "\n".join(lines) + "\n"


def verify_js(name: str, js: str, fn: str, X: np.ndarray, expected: np.ndarray, pick=lambda r: r):
    """Runs the generated JavaScript in Node and compares it with the Python model's predictions."""
    with tempfile.TemporaryDirectory() as tmp:
        (Path(tmp) / "model.mjs").write_text(js)
        (Path(tmp) / "input.json").write_text(json.dumps(X.tolist()))
        (Path(tmp) / "run.mjs").write_text(
            "import * as m from './model.mjs';\nimport { readFileSync } from 'node:fs';\n"
            "const X = JSON.parse(readFileSync(new URL('./input.json', import.meta.url)));\n"
            f"console.log(JSON.stringify(X.map((x) => m.{fn}(x))));\n"
        )
        out = subprocess.run(["node", str(Path(tmp) / "run.mjs")], capture_output=True, text=True)
        if out.returncode != 0:
            raise SystemExit(f"VERIFICATION FAILED for {name}: node error: {out.stderr.strip()[:500]}")
    got = np.array([pick(r) for r in json.loads(out.stdout)], dtype=float)
    err = float(np.max(np.abs(got - expected)))
    if err > 1e-3:
        raise SystemExit(f"VERIFICATION FAILED for {name}: max |js - python| = {err:.5f}")
    print(f"  ✓ {name} verified in Node on {len(X)} rows (max error {err:.2e})")


# XGBoost and scikit-learn trees compare float32 features with float32 thresholds;
# Math.fround reproduces that exactly (otherwise values near a split can take the other branch).
XGB_PREDICT = """
export function predict(input{t_in}){t_out} {{
  const x = input.map(Math.fround);
  const hb = score_median(x);
  const a = score_lower(x);
  const b = score_upper(x);
  // Region from the one-hot just before the [age, sex] demographics (eye, nails, palm).
  const oh = input.slice(-5, -2);
  const cal = CALIBRATION[Math.max(0, oh.indexOf(1))];
  // Quantile models are fit independently and can cross; keep a valid interval around the median,
  // then widen by the conformal offset so ≥80 % of held-out people fall inside.
  return {{ hb, lower: Math.min(a, b, hb) - cal, upper: Math.max(a, b, hb) + cal }};
}}
"""
RF_PREDICT = """
export function predict(input{t_in}){t_out} {{
  return score_rf(input.map(Math.fround));
}}
"""


def export_trees(version: str, dry: bool):
    import xgboost as xgb

    d = np.load(ARTIFACTS / "features.npz", allow_pickle=True)
    from common import region_one_hot

    onehot = np.array([region_one_hot(r) for r in d["region"]])
    from common import demographics

    demo = np.array([demographics(a, s) for a, s in zip(d["age"], d["sex"])])
    X_xgb = np.hstack([d["X_cnn"], d["X_color"], onehot, demo])
    X_rf = np.hstack([d["X_color"], onehot])
    sample = np.random.default_rng(0).choice(len(X_xgb), size=min(50, len(X_xgb)), replace=False)

    models = {}
    for q in ("lower", "median", "upper"):
        m = xgb.XGBRegressor()
        m.load_model(ARTIFACTS / f"xgb_{q}.json")
        models[q] = m
    uses_cnn = bool(d["has_cnn"])
    regions = sorted(set(d["region"].tolist()))
    cal_path = ARTIFACTS / "calibration.json"
    cal = json.loads(cal_path.read_text()) if cal_path.exists() else {}
    cal_js = f"const CALIBRATION = [{cal.get('eye', 0)}, {cal.get('nails', 0)}, {cal.get('palm', 0)}];\n"
    body = "".join(m2cgen_js(models[q], f"score_{q}") for q in ("lower", "median", "upper"))
    probe = cal_js + body + XGB_PREDICT.format(t_in="", t_out="")
    try:
        verify_js("xgboostModel.ts (m2cgen)", probe, "predict", X_xgb[sample], models["median"].predict(X_xgb[sample]), pick=lambda r: r["hb"])
    except SystemExit as e:
        print(f"  ! {e}\n  → using the built-in XGBoost dump translator instead")
        body = "".join(xgb_dump_to_js(models[q], f"score_{q}") for q in ("lower", "median", "upper"))
    date = time.strftime("%Y-%m-%d")
    common_fmt = dict(date=date, version=version, uses_cnn=str(uses_cnn).lower(), regions=json.dumps(regions))
    xgb_ts = HEADER.format(
        desc="XGBoost quantile regressors (alpha 0.1 / 0.5 / 0.9), conformally calibrated — primary model.",
        layout=("[...cnnEmbedding, " if uses_cnn else "[") + "...colorFeatures, eye, nails, palm, ageYears, sex(male=1,female=0,unknown=0.5)]",
        n_features=X_xgb.shape[1],
        uses_demo="true",
        **common_fmt,
    )
    xgb_js = cal_js + body + XGB_PREDICT.format(t_in="", t_out="")
    xgb_ts += "\n" + cal_js + body + XGB_PREDICT.format(t_in=": number[]", t_out=": { hb: number; lower: number; upper: number }")
    rf = joblib.load(ARTIFACTS / "rf.joblib")
    rf_ts = HEADER.format(
        desc="Random Forest on color features only — fallback model.",
        layout="[...colorFeatures, eye, nails, palm]",
        n_features=X_rf.shape[1],
        uses_demo="false",
        **common_fmt,
    )
    rf_body = m2cgen_js(rf, "score_rf")
    rf_js = rf_body + RF_PREDICT.format(t_in="", t_out="")
    rf_ts += "\n" + rf_body + RF_PREDICT.format(t_in=": number[]", t_out=": number")
    target = Path(tempfile.mkdtemp()) if dry else MODELS_TS
    (target / "xgboostModel.ts").write_text(xgb_ts)
    (target / "randomForestModel.ts").write_text(rf_ts)
    verify_js("xgboostModel.ts", xgb_js, "predict", X_xgb[sample], models["median"].predict(X_xgb[sample]), pick=lambda r: r["hb"])
    verify_js("randomForestModel.ts", rf_js, "predict", X_rf[sample], rf.predict(X_rf[sample]))
    print(f"  wrote {target / 'xgboostModel.ts'} ({(target / 'xgboostModel.ts').stat().st_size / 1e6:.1f} MB)")
    print(f"  wrote {target / 'randomForestModel.ts'} ({(target / 'randomForestModel.ts').stat().st_size / 1e6:.1f} MB)")

    # model-info.json: version, CNN (or none), regions, training data and honest metrics.
    info_path = ARTIFACTS / "train_info.json"
    train_info = json.loads(info_path.read_text()) if info_path.exists() else {}
    ds_path = ARTIFACTS / "datasets.json"
    # Colour ranges seen in training (1st–99th percentile) per region, for the app's
    # "photo looks different from the training photos" check.
    ood_feats = ["a_p50", "a_mean", "rg_ratio", "erythema_index", "s_mean", "L_mean"]
    # Separate adult (≥15 y) and child ranges: e.g. the adult eye photos (lens + LED) look much
    # redder than the children's tablet photos, so an adult is compared with adult photos.
    feature_ranges = {}
    ages = d["age"].astype(float)
    for region in regions:
        feature_ranges[region] = {}
        for group, gm in (("adult", ages >= 15), ("child", ages < 15)):
            m = (d["region"] == region) & gm
            if m.sum() < 30:
                continue
            feature_ranges[region][group] = {
                f: [round(float(np.percentile(d["X_color"][m, COLOR_FEATURE_NAMES.index(f)], 1)), 4),
                    round(float(np.percentile(d["X_color"][m, COLOR_FEATURE_NAMES.index(f)], 99)), 4)]
                for f in ood_feats
            }
    info = {
        "version": version,
        "exportedAt": date,
        "featureRanges": feature_ranges,
        "cnn": None if not uses_cnn else {"inputSize": PRE["roiSize"], "normalization": "0_255", "embeddingSize": FEAT["cnnEmbeddingSize"]},
        "regions": regions,
        "metrics": {k: train_info.get(k) for k in ("per_region_mae", "per_region_n", "conformal_offsets", "cv_mae_app")},
        "datasets": json.loads(ds_path.read_text()) if ds_path.exists() else [],
    }
    # Scorecard from model_metrics.py (out-of-fold) — shown in Settings → Model performance.
    metrics_path = ARTIFACTS / "metrics.json"
    if metrics_path.exists():
        info["evaluation"] = json.loads(metrics_path.read_text())
    pub = (target if dry else PUBLIC_MODELS)
    pub.mkdir(parents=True, exist_ok=True)
    (pub / "model-info.json").write_text(json.dumps(info, indent=2))
    print(f"  wrote {pub / 'model-info.json'}")


def export_palm(version: str, dry: bool):
    """Palm anemia CLASSIFIER → src/ml/models/palmClassifier.ts (probability of anemia)."""
    import xgboost as xgb

    info = json.loads((ARTIFACTS / "palm_info.json").read_text())
    clf = xgb.XGBClassifier()
    clf.load_model(ARTIFACTS / "palm_clf.json")
    d = np.load(ARTIFACTS / "palm_features.npz")
    X = d["X"]
    sample = np.random.default_rng(0).choice(len(X), size=min(50, len(X)), replace=False)
    # binary:logistic → probability = sigmoid(logit(base_score) + Σ leaves). The dump translator
    # returns base_score + Σ leaves, so subtract the probability-space base and add its logit.
    base_p = float(json.loads(clf.get_booster().save_config())["learner"]["learner_model_param"]["base_score"])
    body = xgb_dump_to_js(clf, "palm_margin_raw")
    wrapper = f"""
const BASE_P = {base_p!r};
const BASE_MARGIN = Math.log(BASE_P / (1 - BASE_P));
export function predictProbability(input{{t_in}}){{t_out}} {{{{
  const m = palm_margin_raw(input.map(Math.fround)) - BASE_P + BASE_MARGIN;
  return 1 / (1 + Math.exp(-m));
}}}}
"""
    js = body + wrapper.format(t_in="", t_out="")
    verify_js("palmClassifier.ts", js, "predictProbability", X[sample], clf.predict_proba(X[sample])[:, 1])
    header = f"""/* eslint-disable */
// @ts-nocheck
/**
 * GENERATED by training/export.py on {time.strftime("%Y-%m-%d")} — do not edit by hand.
 * Palm pallor classifier: probability that the palm looks anemic (Hb < 11 g/dL in the training
 * children). Trained on {info["dataset"]["name"]} (doi:{info["dataset"]["doi"]}, {info["dataset"]["license"]}).
 * Input: colour features (same layout as the app). No hemoglobin value is produced.
 */
export const IS_PLACEHOLDER: boolean = false;
export const MODEL_VERSION: string = '{version}';
export const FEATURE_COUNT: number = {X.shape[1]};
/** Probability at or above this = "looks anemic" (balanced sensitivity/specificity on held-out photos). */
export const THRESHOLD: number = {info["threshold"]};
export const METRICS = {{ auc: {info["auc"]}, sensitivity: {info["sensitivity"]}, specificity: {info["specificity"]} }};
export const POPULATION = {{ minAge: {info["dataset"]["minAge"]}, maxAge: {info["dataset"]["maxAge"]}, description: {json.dumps(info["dataset"]["population"], ensure_ascii=False)} }};
"""
    target = Path(tempfile.mkdtemp()) if dry else MODELS_TS
    (target / "palmClassifier.ts").write_text(header + "\n" + body + wrapper.format(t_in=": number[]", t_out=": number"))
    print(f"  wrote {target / 'palmClassifier.ts'} ({(target / 'palmClassifier.ts').stat().st_size / 1e6:.1f} MB)")
    # Record the palm dataset + metrics in model-info.json (shown in the app's model note).
    mi_path = (target if dry else PUBLIC_MODELS) / "model-info.json"
    mi = json.loads(mi_path.read_text()) if mi_path.exists() else {"version": version, "datasets": [], "metrics": {}}
    mi["datasets"] = [ds for ds in mi.get("datasets", []) if ds.get("region") != "palm"] + [
        {**info["dataset"], "region": "palm", "n": info["dataset"]["photos"], "kind": "classifier"}
    ]
    mi.setdefault("metrics", {})["palm_classifier"] = {k: info[k] for k in ("auc", "sensitivity", "specificity", "threshold")}
    mi_path.write_text(json.dumps(mi, indent=2, ensure_ascii=False))
    print(f"  updated {mi_path}")


def export_cnn(version: str, dry: bool):
    import tensorflow as tf

    size = PRE["roiSize"]
    finetuned = ARTIFACTS / "cnn_finetuned.keras"
    model = (
        tf.keras.models.load_model(finetuned)
        if finetuned.exists()
        else tf.keras.applications.MobileNetV3Small(input_shape=(size, size, 3), include_top=False, pooling="avg", weights="imagenet", include_preprocessing=True)
    )
    out_dir = (Path(tempfile.mkdtemp()) if dry else PUBLIC_MODELS) / "cnn"
    with tempfile.TemporaryDirectory() as tmp:
        saved = Path(tmp) / "saved_model"

        @tf.function(input_signature=[tf.TensorSpec([None, size, size, 3], tf.float32, name="image")])
        def serve(x):
            return {"embedding": model(x, training=False)}

        tf.saved_model.save(model, str(saved), signatures={"serving_default": serve})
        if out_dir.exists():
            shutil.rmtree(out_dir)
        cmd = [
            "tensorflowjs_converter",
            "--input_format=tf_saved_model",
            "--output_format=tfjs_graph_model",
            "--signature_name=serving_default",
            "--quantize_uint8=*",
            str(saved),
            str(out_dir),
        ]
        subprocess.run(cmd, check=True)
    info = {
        "version": version,
        "cnn": {"inputSize": size, "normalization": "0_255", "embeddingSize": FEAT["cnnEmbeddingSize"], "architecture": model.name},
        "exportedAt": time.strftime("%Y-%m-%d"),
    }
    (out_dir.parent / "model-info.json").write_text(json.dumps(info, indent=2))
    total = sum(f.stat().st_size for f in out_dir.iterdir()) / 1e6
    print(f"  ✓ CNN → {out_dir} ({total:.1f} MB) + model-info.json")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--version", default=time.strftime("%Y.%m.%d"))
    ap.add_argument("--skip-cnn", action="store_true")
    ap.add_argument("--skip-trees", action="store_true")
    ap.add_argument("--palm", action="store_true", help="also export the palm anemia classifier")
    ap.add_argument("--dry-run", action="store_true", help="write to a temp folder instead of the app")
    args = ap.parse_args()
    if not args.skip_trees:
        print("Exporting tree models (m2cgen) …")
        export_trees(args.version, args.dry_run)
    if args.palm:
        print("Exporting palm classifier …")
        export_palm(args.version, args.dry_run)
    if not args.skip_cnn:
        print("Exporting CNN (TF.js graph model) …")
        export_cnn(args.version, args.dry_run)
    print("\nDone. Rebuild the app (npm run build).")


if __name__ == "__main__":
    main()
